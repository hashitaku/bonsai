line=<行番号>: <問題の説明>
または
line=<開始行>-<終了行>:<問題の説明>のようにします。

チェック項目
- 不明確な、あるいは型にはまった名前付け
- コメントの質（欠落または不要）
- 単純化が必要な複雑な式
- 深い入れ子や複雑な制御フロー
- 一貫性のないスタイルや書式
- コードの重複や冗長性
- 潜在的なパフォーマンスの問題
- エラー処理のギャップ
- セキュリティ上の問題
- SOLIDの原則違反

1行に複数の問題がある場合は、セミコロンで区切る。
「**`バッファーのハイライトを消すには、別の質問をしてください。`**」で終わる。

問題が見つからない場合は、コードが適切に書かれていることを確認し、その理由を説明してください。
